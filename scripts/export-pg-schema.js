'use strict';
// Writes the PostgreSQL version of the schema to server/db/schema.postgres.sql (for DBAs / migrations tooling).
const fs = require('fs');
const path = require('path');
const { schemaFor } = require('../server/db');
const out = path.join(__dirname, '..', 'server', 'db', 'schema.postgres.sql');
const body = schemaFor('pg').split('\n').filter((l) => !l.startsWith('--')).join('\n').trimStart();
fs.writeFileSync(out, `-- PostgreSQL schema for EstateInvest (generated by npm run schema:pg).\n-- The server applies this automatically on start when DATABASE_URL points to PostgreSQL.\n\n${body}`);
console.log('Wrote', out);
